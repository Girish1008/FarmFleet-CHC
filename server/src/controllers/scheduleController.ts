import { Response, NextFunction } from 'express';
import { AuthenticatedRequest } from '../middleware/auth.js';
import { store } from '../services/db.js';
import { SlotRecommender } from '../services/ai/slotRecommender.js';
import { DynamicRescheduler } from '../services/ai/dynamicRescheduler.js';
import { ProposalReason } from '../types/index.js';

export class ScheduleController {
  static async getSchedule(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const { machineId, operatorId, date, view = 'week' } = req.query;

      let bookings = store.bookings.filter(b => b.status !== 'CANCELLED');

      if (machineId) {
        bookings = bookings.filter(b => b.machineId === machineId);
      }
      if (operatorId) {
        bookings = bookings.filter(b => b.operatorId === operatorId);
      }
      if (date) {
        const targetDate = new Date(date as string).toISOString().split('T')[0];
        bookings = bookings.filter(
          b => new Date(b.scheduledStart).toISOString().split('T')[0] === targetDate
        );
      }

      res.json({
        data: bookings,
      });
    } catch (err) {
      next(err);
    }
  }

  static async recommendSlots(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const { machineId, preferredDate, areaInAcres, location, cropType } = req.query;

      if (!preferredDate) {
        res.status(400).json({
          error: {
            code: 'BAD_REQUEST',
            message: 'preferredDate query parameter is required',
          },
        });
        return;
      }

      const area = parseFloat((areaInAcres as string) || '4');
      const slots = SlotRecommender.recommendSlots({
        machineId: machineId as string,
        preferredDate: preferredDate as string,
        areaInAcres: area,
        location: (location as string) || 'Sultanpur',
        cropType: (cropType as string) || 'Wheat',
      });

      res.json({
        data: slots,
      });
    } catch (err) {
      next(err);
    }
  }

  static async listProposals(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const pendingProposals = store.proposals.filter(p => p.status === 'PENDING');
      res.json({
        data: pendingProposals,
      });
    } catch (err) {
      next(err);
    }
  }

  static async proposeReschedule(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const { reason = 'BREAKDOWN', scope = {} } = req.body;
      const proposal = DynamicRescheduler.proposeReschedule(reason as ProposalReason, scope);

      res.status(201).json({
        data: proposal,
        message: 'Schedule change proposal generated by AI scheduler',
      });
    } catch (err) {
      next(err);
    }
  }

  static async acceptReschedule(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const { proposalId } = req.body;
      if (!proposalId) {
        res.status(400).json({
          error: {
            code: 'BAD_REQUEST',
            message: 'proposalId is required',
          },
        });
        return;
      }

      DynamicRescheduler.acceptProposal(proposalId);
      res.json({
        success: true,
        message: 'Reschedule proposal accepted and applied to active bookings',
      });
    } catch (err) {
      next(err);
    }
  }

  static async rejectReschedule(req: AuthenticatedRequest, res: Response, next: NextFunction): Promise<void> {
    try {
      const { proposalId } = req.body;
      if (!proposalId) {
        res.status(400).json({
          error: {
            code: 'BAD_REQUEST',
            message: 'proposalId is required',
          },
        });
        return;
      }

      DynamicRescheduler.rejectProposal(proposalId);
      res.json({
        success: true,
        message: 'Reschedule proposal rejected',
      });
    } catch (err) {
      next(err);
    }
  }
}
